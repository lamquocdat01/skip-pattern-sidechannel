"""align.py — T22b Task 1: put the real INA219 trace on the video time axis and calibrate it.

Input : results/real_trace/raw/<RUN>/ (dump of fw_replay: trace_<tag>.csv, sched_<tag>.csv, meta.json,
        dump_manifest.json) and results/real_trace/replay_selection.csv (sha256 of every schedule).
Output: results/real_trace/aligned_<tag>.csv  one row per 10-Hz sample of the replay phase:
          t_real (s since the schedule started), t_video (= frame / fps_video), frame, a_t (open bit of that frame),
          a_prev (open bit of the previous frame), e_t (ground-truth event bit), bus_V, shunt_mV, I_mA
        results/real_trace/calib.json         idle current, open-vs-closed current step, energy per open.

Each sample is a 68.1-ms shunt-ADC average that ends at the read; the read happens in frame `frame`, so the window
covers the end of frame-1 and the start of frame. The open/closed step is therefore estimated on samples whose
current and previous frame agree (both open vs both closed), median over samples.

Usage: python align.py [--run 20261013T161503Z]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

import gates as G  # noqa: E402
from data_sparse import load_c121, load_virat  # noqa: E402
from schedules import load_config, results_dir  # noqa: E402

CFG = load_config()
OUT = results_dir(CFG) / "real_trace"
RUN_DEFAULT = "20261013T161503Z"
I_LSB_MA, SHUNT_LSB_MV, BUS_LSB_V = 0.1, 0.01, 0.004


def selection() -> pd.DataFrame:
    return pd.read_csv(OUT / "replay_selection.csv")


def clip_of(dataset: str, video: str):
    pool = load_virat(CFG) if dataset == "VIRAT" else load_c121(CFG)
    return next(c for c in pool if c.dataset == dataset and c.video == video)


def check_run(run_dir: Path, sel: pd.DataFrame, clips: dict) -> dict:
    """Integrity: dump CRCs ok, schedules on the device == schedules generated by the host == G3 recomputed now."""
    man = json.loads((run_dir / "dump_manifest.json").read_text(encoding="utf-8"))
    assert all(f["crc_ok"] for f in man["files"]), "dump has CRC mismatches"
    meta = json.loads((run_dir / "meta.json").read_text(encoding="utf-8"))
    for r in sel.itertuples():
        raw = (run_dir / f"sched_{r.tag}.csv").read_bytes()
        assert hashlib.sha256(raw).hexdigest() == r.sha256, f"{r.tag}: device schedule differs from selection"
        a_dev = pd.read_csv(run_dir / f"sched_{r.tag}.csv").a_t.to_numpy()
        c = clips[r.tag]
        assert np.array_equal(a_dev, G.deployed(c.score, c.valid).astype(int)), f"{r.tag}: G3 replay changed"
    ms = {s["tag"]: s for s in meta["schedules"]}
    for tag, s in ms.items():
        assert s["overruns"] == 0 and s["n_open_executed"] == s["n_open_schedule"], f"{tag}: replay not exact"
    assert meta["i2c_errors"] == 0 and meta["samples_overflow"] == 0
    return meta


def load_trace(run_dir: Path, tag: str) -> pd.DataFrame:
    x = pd.read_csv(run_dir / f"trace_{tag}.csv")
    x["I_mA"] = x.cur_raw * I_LSB_MA
    x["shunt_mV"] = x.shunt_raw * SHUNT_LSB_MV
    x["bus_V"] = (x.bus_raw.to_numpy() >> 3) * BUS_LSB_V
    return x


def align(run: str = RUN_DEFAULT) -> dict:
    run_dir = OUT / "raw" / run
    sel = selection()
    clips = {r.tag: clip_of(r.dataset, r.video) for r in sel.itertuples()}
    meta = check_run(run_dir, sel, clips)
    ms = {s["tag"]: s for s in meta["schedules"]}

    idle, steps, volts, per_video = [], [], [], {}
    for r in sel.itertuples():
        c = clips[r.tag]
        a = c_a = G.deployed(c.score, c.valid).astype(np.int8)
        x = load_trace(run_dir, r.tag)
        play = x[x.phase == 1].copy()
        k = play.frame.to_numpy()
        play["t_real"] = (play.t_ms - ms[r.tag]["t_start_ms"]) / 1000.0
        play["t_video"] = k / c.fps
        play["a_t"] = c_a[k]
        play["a_prev"] = np.r_[0, c_a][k]                     # a[k-1], 0 before the first frame
        play["e_t"] = c.e[k]
        cols = ["t_real", "t_video", "frame", "a_t", "a_prev", "e_t", "bus_V", "shunt_mV", "I_mA"]
        play[cols].to_csv(OUT / f"aligned_{r.tag}.csv", index=False, float_format="%.4f")

        tail = x[x.phase == 2]
        idle.append(tail.I_mA.to_numpy())
        both1 = play.I_mA[(play.a_t == 1) & (play.a_prev == 1)]
        both0 = play.I_mA[(play.a_t == 0) & (play.a_prev == 0)]
        steps.append((both1.to_numpy(), both0.to_numpy()))
        volts.append(play.bus_V.to_numpy())
        per_video[r.tag] = dict(
            n_samples=int(len(play)), n_frames=int(c.n), fps_video=float(c.fps), rho=round(float(a.mean()), 4),
            samples_per_video_s=round(float(len(play) / (c.n / c.fps)), 2),
            I_idle_median_mA=round(float(np.median(tail.I_mA)), 2), I_idle_sd_mA=round(float(tail.I_mA.std()), 3),
            I_open_median_mA=round(float(np.median(both1)), 2), I_closed_median_mA=round(float(np.median(both0)), 2),
            dI_frame_mA=round(float(np.median(both1) - np.median(both0)), 2),
            n_both_open=int(len(both1)), n_both_closed=int(len(both0)),
            corr_I_a=round(float(np.corrcoef(play.I_mA, play.a_t + play.a_prev)[0, 1]), 3))

    I_idle = float(np.median(np.concatenate(idle)))
    I_open = float(np.median(np.concatenate([s[0] for s in steps])))
    I_closed = float(np.median(np.concatenate([s[1] for s in steps])))
    dI = I_open - I_closed
    V = float(np.mean(np.concatenate(volts)))
    period_s = 1.0 / float(meta["fps_play"])
    busy_s = float(meta["busy_ms"]) / 1000.0
    dI_busy = dI * period_s / busy_s                     # frame-averaged step -> step while the busy loop runs
    E_open_mJ = V * dI_busy * busy_s                      # = V * dI * period
    calib = dict(
        run=run, fw=meta["fw"], fps_play=meta["fps_play"], busy_ms=meta["busy_ms"], sample_hz=meta["sample_hz"],
        warmup_mean_mA=round(float(meta["warmup_mean_mA"]), 2), samples_total=int(meta["samples_total"]),
        overruns=int(sum(s["overruns"] for s in meta["schedules"])), i2c_errors=int(meta["i2c_errors"]),
        busy_ms_mean=round(float(np.mean([s["busy_ms_mean"] for s in meta["schedules"]])), 3),
        I_idle_mA=round(I_idle, 2), I_idle_sd_mA=round(float(np.concatenate(idle).std()), 3),
        I_open_mA=round(I_open, 2), I_closed_mA=round(I_closed, 2),
        I_closed_minus_idle_mA=round(I_closed - I_idle, 2),
        dI_frame_mA=round(dI, 2), dI_busy_mA=round(dI_busy, 2), V_mean=round(V, 3),
        V_min=round(float(np.concatenate(volts).min()), 3), V_max=round(float(np.concatenate(volts).max()), 3),
        dP_busy_mW=round(V * dI_busy, 1), E_open_mJ=round(E_open_mJ, 2),
        E_open_over_deep3_E_active=round(E_open_mJ / float(CFG["observer"]["E_active_mJ"]), 3),
        P_idle_mW=round(V * I_idle, 1),
        note=("whole-board current at the 5-V pin (includes CH343 USB bridge and INA219 supply, ~1 mA); "
              "camera not running; dI from samples whose current and previous frame agree"),
        per_video=per_video)
    (OUT / "calib.json").write_text(json.dumps(calib, indent=1), encoding="utf-8")
    return calib


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default=RUN_DEFAULT)
    calib = align(ap.parse_args().run)
    print(json.dumps({k: v for k, v in calib.items() if k != "per_video"}, indent=1))
    print(pd.DataFrame(calib["per_video"]).T.to_string())


if __name__ == "__main__":
    main()
